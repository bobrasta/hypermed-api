    public function run(): void
    {
        $first = self::COORDS[array_key_first(self::COORDS)];
        $already = Hospital::where('short_code', array_key_first(self::COORDS))
            ->where('latitude', $first[0])
            ->exists();
        if ($already) {
            return;
        }

        foreach (self::COORDS as $code => [$lat, $lng]) {
            Hospital::where('short_code', $code)->update([
                'latitude' => $lat, 'longitude' => $lng,
            ]);
        }
    }
